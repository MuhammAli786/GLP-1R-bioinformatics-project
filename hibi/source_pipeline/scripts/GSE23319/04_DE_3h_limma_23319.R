############################################################
## Differential Expression Analysis
## GSE23319
## 3 h HI vs Sham
############################################################

library(limma)

############################################################
# Load data
############################################################

gse <- readRDS("data/GSE23319.rds")

eset <- gse[[1]]

expr <- exprs(eset)

pheno <- pData(eset)

############################################################
# Keep only 3-hour Sham and HI samples
############################################################

keep <- grepl("3h", pheno$title) &
  (grepl("Sham", pheno$title) |
     grepl("HI-", pheno$title))

expr_sub <- expr[, keep]

pheno_sub <- pheno[keep, ]

############################################################
# Create experimental groups
############################################################

group <- ifelse(
  grepl("Sham", pheno_sub$title),
  "Sham",
  "HI"
)

group <- factor(group)

table(group)

############################################################
# Design matrix
############################################################

design <- model.matrix(~group)

design

############################################################
# Differential expression
############################################################

fit <- lmFit(expr_sub, design)

fit <- eBayes(fit)

############################################################
# Extract results
############################################################

results <- topTable(
  fit,
  coef = 2,
  number = Inf,
  adjust.method = "BH"
)

############################################################
# Save all genes
############################################################

write.csv(
  results,
  "results/GSE23319_3h_all_genes.csv"
)

############################################################
# Significant DEGs
############################################################

deg <- subset(
  results,
  abs(logFC) >= 0.2 &
    adj.P.Val < 0.05
)

############################################################
# Save DEGs
############################################################

write.csv(
  deg,
  "results/GSE23319_3h_DEGs.csv"
)

############################################################
# Summary
############################################################

cat("Number of DEGs:", nrow(deg), "\n")